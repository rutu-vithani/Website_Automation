def _extract_python_block(text: str) -> str:
    import re
    match = re.search(r"```python\s*(.*?)```", text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()
    generic = re.search(r"```\s*(.*?)```", text, re.DOTALL)
    return generic.group(1).strip() if generic else ""


class BackendAgent:
    def __init__(self, nvidia_client: NvidiaClient = None):
        self.nvidia = nvidia_client or NvidiaClient()

    def generate_extra_routes(self, brief: dict) -> str:
        prompt = f"Business brief: {brief}\nGenerate any extra /api/ routes this business specifically needs (e.g. /api/pricing, /api/testimonials GET)."
        try:
            response = self.nvidia.code(EXTRA_ROUTES_SYSTEM_PROMPT, prompt, temperature=0.3, max_tokens=2000)
            code = _extract_python_block(response)
            return code if code else "# no extra routes generated"
        except Exception:
            return "# extra route generation skipped (nvidia api unavailable)"

    def build(self, project_slug: str, brief: dict, runtime_collections: dict) -> str:
        extra_routes = self.generate_extra_routes(brief)
        app_py = APP_TEMPLATE.format(
            business_name=brief.get("business_name", "Generated Website"),
            project_slug=project_slug,
            contact_collection=runtime_collections["contact_collection"],
            testimonials_collection=runtime_collections["testimonials_collection"],
            site_content_collection=runtime_collections["site_content_collection"],
            extra_routes=extra_routes,
        )
        return app_py

    def write_to_disk(self, project_dir: str, app_py: str):
        os.makedirs(project_dir, exist_ok=True)
        with open(os.path.join(project_dir, "app.py"), "w", encoding="utf-8") as f:
            f.write(app_py)
        # requirements + a project-local .env.example so the user knows what to fill
        with open(os.path.join(project_dir, "requirements.txt"), "w", encoding="utf-8") as f:
            f.write("flask\nflask-cors\npymongo\npython-dotenv\n")
        env_example_path = os.path.join(project_dir, ".env.example")
        if not os.path.exists(env_example_path):
            with open(env_example_path, "w", encoding="utf-8") as f:
                f.write(
                    "MONGO_URI=mongodb://localhost:27017\n"
                    "MONGO_DB_NAME=generated_website_db\n"
                    "# Password to log in at http://localhost:5000/admin\n"
                    "ADMIN_PASSWORD=admin123\n"
                    "# Optional: fixed Flask session secret (auto-generated per run if left blank)\n"
                    "ADMIN_SECRET_KEY=\n"
                )