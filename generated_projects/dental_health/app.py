@app.route("/admin")
def admin_panel():
    return send_from_directory(FRONTEND_DIR, "admin.html")


@app.route("/details/<detail_id>")
def details_page(detail_id):
    return send_from_directory(FRONTEND_DIR, "details.html")


@app.route("/api/content")
def public_content():
    # Public, read-only: the live page's own script loads this to apply any
    # edits made in the admin panel. Contains nothing not already visible on
    # the page itself.
    return jsonify(_load_content())


@app.route("/api/details/<detail_id>")
def api_detail(detail_id):
    data = _load_content()
    for item in data.get("details", []):
        if item.get("id") == detail_id:
            return jsonify(item)
    return jsonify({"error": "not found"}), 404


@app.route("/api/admin/login", methods=["POST"])
def admin_login():
    payload = request.get_json(force=True, silent=True) or {}
    if payload.get("password") == ADMIN_PASSWORD:
        session["is_admin"] = True
        return jsonify({"success": True})
    return jsonify({"success": False, "error": "Incorrect password"}), 401


@app.route("/api/admin/logout", methods=["POST"])
def admin_logout():
    session.pop("is_admin", None)
    return jsonify({"success": True})


@app.route("/api/admin/content", methods=["GET", "POST"])
def admin_content():
    if not _require_admin():
        return jsonify({"success": False, "error": "Not authenticated"}), 401

    if request.method == "GET":
        return jsonify(_load_content())

    payload = request.get_json(force=True, silent=True) or {}
    data = _load_content()
    if "editable" in payload and isinstance(payload["editable"], dict):
        data["editable"].update(payload["editable"])
    if "details" in payload and isinstance(payload["details"], list):
        data["details"] = payload["details"]
    _save_content(data)
    return jsonify({"success": True})


