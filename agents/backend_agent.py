load_dotenv()

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
FRONTEND_DIR = os.path.join(BASE_DIR, "frontend")
CONTENT_FILE = os.path.join(FRONTEND_DIR, "content.json")

app = Flask(__name__, static_folder=FRONTEND_DIR, static_url_path="")
app.secret_key = os.environ.get("ADMIN_SECRET_KEY") or secrets.token_hex(32)
CORS(app, supports_credentials=True)

ADMIN_PASSWORD = os.environ.get("ADMIN_PASSWORD", "admin123")

mongo_client = MongoClient(os.environ.get("MONGO_URI", "mongodb://localhost:27017"))
db = mongo_client[os.environ.get("MONGO_DB_NAME", "generated_website_db")]

PROJECT_SLUG = "{project_slug}"
db_collections = {{
    "contact_messages": db["{contact_collection}"],
    "testimonials": db["{testimonials_collection}"],
    "site_content": db["{site_content_collection}"],
}}


def _default_content():
    return {{"editable": {{}}, "details": [], "sections": [], "custom_fields": {{}}}}


def _normalize_content(data: dict) -> dict:
    # Backfills keys for content.json files written before "sections" /
    # "custom_fields" existed, so older generated projects keep working.
    data.setdefault("editable", {{}})
    data.setdefault("details", [])
    data.setdefault("sections", [])
    data.setdefault("custom_fields", {{}})
    return data


def _load_content():
    if os.path.exists(CONTENT_FILE):
        try:
            with open(CONTENT_FILE, "r", encoding="utf-8") as f:
                return _normalize_content(json.load(f))
        except Exception:
            pass
    doc = db_collections["site_content"].find_one({{"project_slug": PROJECT_SLUG, "_key": "main"}})
    if doc:
        return _normalize_content({{
            "editable": doc.get("editable", {{}}),
            "details": doc.get("details", []),
            "sections": doc.get("sections", []),
            "custom_fields": doc.get("custom_fields", {{}}),
        }})
    return _default_content()


def _save_content(data: dict):
    os.makedirs(FRONTEND_DIR, exist_ok=True)
    with open(CONTENT_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
    try:
        db_collections["site_content"].update_one(
            {{"project_slug": PROJECT_SLUG, "_key": "main"}},
            {{"$set": {{**data, "project_slug": PROJECT_SLUG, "_key": "main"}}}},
            upsert=True,
        )
    except Exception:
        pass  # the JSON file on disk is still the source of truth


def _require_admin():
    return session.get("is_admin") is True


@app.route("/")
def home():
    # Serves index.html with a clean root URL — never /index.html
    return send_from_directory(FRONTEND_DIR, "index.html")


